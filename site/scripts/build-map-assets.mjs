#!/usr/bin/env node
/**
 * Copies the Disha app's own map style into public/map/, so the site's maps look like the app's.
 * Run it from site/ when the app's style changes:
 *
 *   node scripts/build-map-assets.mjs [--ios ../../disha-ios] [--me ../../me]
 *
 * It writes the three map layers the site offers (src/lib/map/layers.ts):
 * - Terrain, public/map/style-light.json and style-dark.json: the app's disha-outdoor-osm styles
 *   (the OSM world map, relief and national routes to z8, then the cells, with hillshade and
 *   contours), their sources pointed at the site's disha:// protocol (src/lib/map/disha-protocol.ts).
 * - OpenFreeMap, public/map/ofm-light.json and ofm-dark.json: andrewpham.dev's trail style
 *   (me public/map-styles/outdoor-terrain-open*.json) on OpenFreeMap's data, with the cells'
 *   hillshade and contours in the same paint me gives them (OPEN_TERRAIN_PAINT in me
 *   src/lib/map/styles.ts). It fills the ground outside the published cells.
 * - OSM Classic is OpenStreetMap's raster tiles, built in layers.ts; nothing to copy.
 * - public/map/fonts/ and the sprite: the app's bundled Noto Sans glyphs (OFL) and POI icons.
 *
 * No tiles are copied. The browser reads the world map and the cells from tiles.hikaya.app.
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`)
  return resolve(SITE, i > 0 ? process.argv[i + 1] : fallback)
}
const IOS = join(arg('ios', '../../disha-ios'), 'Disha/Resources')
const ME = join(arg('me', '../../me'), 'public/map-styles')
const OUT = join(SITE, 'public/map')

/**
 * The world map files' top zoom. MapLibre enlarges z7 at z8, and the style's world layers stop at
 * z9, where the cells start (disha_ios MapZoomPolicy.overviewMaximum is 8).
 */
const WORLD_MAX_ZOOM = 7

function convertStyle(file, out) {
  const style = JSON.parse(readFileSync(join(IOS, file), 'utf8'))
  style.name = `Disha site (${out.includes('dark') ? 'dark' : 'light'})`
  // Absolute at runtime: CoverageMap prefixes the page origin, since MapLibre wants full URLs.
  style.glyphs = '/map/fonts/{fontstack}/{range}.pbf'
  style.sprite = '/map/sprite'
  style.metadata = {
    note: `Generated by site/scripts/build-map-assets.mjs from disha_ios ${file}. Don't edit by hand.`,
  }
  // Attributions live in the map caption, so the sources carry none.
  style.sources = {
    world: {
      type: 'vector',
      tiles: ['disha://world/{z}/{x}/{y}'],
      minzoom: 0,
      maxzoom: WORLD_MAX_ZOOM,
    },
    relief: {
      type: 'raster',
      tiles: ['disha://relief/{z}/{x}/{y}'],
      tileSize: 256,
      minzoom: 0,
      maxzoom: WORLD_MAX_ZOOM,
    },
    'world-routes': {
      type: 'vector',
      tiles: ['disha://world-routes/{z}/{x}/{y}'],
      minzoom: 0,
      maxzoom: WORLD_MAX_ZOOM,
    },
    // Terrain and contours start at z10: a z9 tile spans four cells, and merging raster tiles
    // means decoding pixels, which Safari adds noise to (see the maplibre-maps skill).
    'hillshade-source': {
      type: 'raster-dem',
      tiles: ['disha://terrain/{z}/{x}/{y}'],
      tileSize: 512,
      encoding: 'terrarium',
      minzoom: 10,
      maxzoom: 12,
    },
    contour: { type: 'vector', tiles: ['disha://contours/{z}/{x}/{y}'], minzoom: 11, maxzoom: 14 },
    openmaptiles: {
      type: 'vector',
      tiles: ['disha://basemap/{z}/{x}/{y}'],
      minzoom: 9,
      maxzoom: 14,
    },
    hiking: { type: 'vector', tiles: ['disha://hiking/{z}/{x}/{y}'], minzoom: 10, maxzoom: 14 },
    routes: { type: 'vector', tiles: ['disha://routes/{z}/{x}/{y}'], minzoom: 9, maxzoom: 14 },
  }
  const missing = style.layers.filter((l) => l.source && !style.sources[l.source])
  if (missing.length) {
    throw new Error(
      `${file}: layers use unknown sources: ${missing.map((l) => l.source).join(', ')}`,
    )
  }
  writeFileSync(join(OUT, out), `${JSON.stringify(style, null, 2)}\n`)
  return style.layers.length
}

/** me's hillshade and contour paint (OPEN_TERRAIN_PAINT in me src/lib/map/styles.ts). */
const OPEN_TERRAIN_PAINT = {
  light: {
    hillshade: {
      'hillshade-illumination-direction': 315,
      'hillshade-illumination-anchor': 'viewport',
      'hillshade-exaggeration': 0.3,
      'hillshade-shadow-color': '#333333',
      'hillshade-highlight-color': '#ffffff',
      'hillshade-accent-color': '#d4d4d4',
    },
    contour: '#c2b49a',
    contourMajor: '#b09e7e',
    label: { 'text-color': '#8a7a5e', 'text-halo-color': 'rgba(255, 255, 255, 0.8)' },
    opacity: { medium: [0.28, 0.4], minor: [0.25, 0.4], major: [0.3, 0.5, 0.6] },
  },
  dark: {
    hillshade: {
      'hillshade-illumination-direction': 315,
      'hillshade-illumination-anchor': 'viewport',
      'hillshade-exaggeration': 0.35,
      'hillshade-shadow-color': '#000000',
      'hillshade-highlight-color': '#6b7280',
      'hillshade-accent-color': '#3a3f46',
    },
    contour: '#5a4f3a',
    contourMajor: '#6f6147',
    label: { 'text-color': '#a79468', 'text-halo-color': 'rgba(16, 18, 20, 0.8)' },
    opacity: { medium: [0.3, 0.45], minor: [0.28, 0.45], major: [0.35, 0.55, 0.65] },
  },
}

const zoomRamp = (...stops) => ['interpolate', ['linear'], ['zoom'], ...stops]

function convertOpenStyle(file, out, theme) {
  const style = JSON.parse(readFileSync(join(ME, file), 'utf8'))
  const p = OPEN_TERRAIN_PAINT[theme]
  style.name = `Disha site OpenFreeMap (${theme})`
  style.glyphs = '/map/fonts/{fontstack}/{range}.pbf'
  style.metadata = {
    note: `Generated by site/scripts/build-map-assets.mjs from me ${file}. Don't edit by hand.`,
  }
  // OpenFreeMap's data for the base map; the cells' terrain and contours through disha://, from
  // z10 and z11 as on the Terrain layer.
  style.sources = {
    openmaptiles: { type: 'vector', url: 'https://tiles.openfreemap.org/planet' },
    'hillshade-source': {
      type: 'raster-dem',
      tiles: ['disha://terrain/{z}/{x}/{y}'],
      tileSize: 512,
      encoding: 'terrarium',
      minzoom: 10,
      maxzoom: 12,
    },
    contour: { type: 'vector', tiles: ['disha://contours/{z}/{x}/{y}'], minzoom: 11, maxzoom: 14 },
  }
  const contour = (id, minzoom, filter, color, width, opacity) => ({
    id,
    type: 'line',
    source: 'contour',
    'source-layer': 'contour',
    minzoom,
    filter,
    paint: { 'line-color': color, 'line-width': width, 'line-opacity': opacity },
  })
  // Where me puts them: hillshade and contour lines under the buildings and roads, the contour
  // labels under the first real label.
  const relief = [
    { id: 'hillshade', type: 'hillshade', source: 'hillshade-source', paint: p.hillshade },
    contour(
      'contour-medium',
      12,
      ['==', 'nth_line', 50],
      p.contour,
      zoomRamp(12, 0.4, 14, 0.7),
      zoomRamp(12, p.opacity.medium[0], 14, p.opacity.medium[1]),
    ),
    contour(
      'contour-minor',
      13,
      ['<', 'nth_line', 50],
      p.contour,
      zoomRamp(13, 0.4, 14, 0.8),
      zoomRamp(13, p.opacity.minor[0], 14, p.opacity.minor[1]),
    ),
    contour(
      'contour-major',
      11,
      ['>=', 'nth_line', 100],
      p.contourMajor,
      zoomRamp(11, 0.6, 12, 1, 14, 1.4),
      zoomRamp(11, p.opacity.major[0], 12, p.opacity.major[1], 14, p.opacity.major[2]),
    ),
  ]
  const label = {
    id: 'contour-label',
    type: 'symbol',
    source: 'contour',
    'source-layer': 'contour',
    minzoom: 12,
    filter: ['>=', 'nth_line', 100],
    layout: {
      'symbol-placement': 'line',
      'text-field': ['concat', ['to-string', ['get', 'ele']], ' m'],
      'text-font': ['Noto Sans Regular'],
      'text-size': zoomRamp(12, 9, 14, 11),
      'text-max-angle': 25,
      'text-padding': 5,
      'text-optional': true,
      'symbol-spacing': 250,
    },
    paint: { ...p.label, 'text-halo-width': 1.5 },
  }
  const at = (id) => {
    const i = style.layers.findIndex((l) => l.id === id)
    if (i < 0) throw new Error(`${file}: no ${id} layer to anchor the terrain to`)
    return i
  }
  style.layers.splice(at('building'), 0, ...relief)
  const firstLabel = style.layers.findIndex((l) => l.type === 'symbol' && !l.id.startsWith('ne-'))
  style.layers.splice(firstLabel, 0, label)

  const missing = style.layers.filter((l) => l.source && !style.sources[l.source])
  if (missing.length) throw new Error(`${file}: unknown sources ${missing.map((l) => l.source)}`)
  writeFileSync(join(OUT, out), `${JSON.stringify(style, null, 2)}\n`)
  return style.layers.length
}

mkdirSync(OUT, { recursive: true })
const light = convertStyle('disha-outdoor-osm.json', 'style-light.json')
const dark = convertStyle('disha-outdoor-osm-dark.json', 'style-dark.json')
const ofmLight = convertOpenStyle('outdoor-terrain-open.json', 'ofm-light.json', 'light')
const ofmDark = convertOpenStyle('outdoor-terrain-open-dark.json', 'ofm-dark.json', 'dark')
rmSync(join(OUT, 'fonts'), { recursive: true, force: true })
// The app's fonts README is about its own build; only the glyphs and their license come over.
cpSync(join(IOS, 'fonts'), join(OUT, 'fonts'), {
  recursive: true,
  filter: (src) => !src.endsWith('README.md'),
})
for (const f of ['sprite.json', 'sprite.png', 'sprite@2x.json', 'sprite@2x.png']) {
  cpSync(join(IOS, f), join(OUT, f))
}
console.log(`Terrain: ${light} light and ${dark} dark layers.`)
console.log(`OpenFreeMap: ${ofmLight} light and ${ofmDark} dark layers.`)
